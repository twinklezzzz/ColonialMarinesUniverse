using System.Linq;
using Content.Client.CMU14.Interface;
using Content.Client.Lobby.UI;
using Content.Shared.CMU14.CorporateWork;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.CorporateWork;

[GenerateTypedNameReferences]
public sealed partial class CMUMarketsTerminalWindow : DefaultWindow
{
    [Dependency] private IGameTiming _timing = default!;

    private static readonly int[] Quick = { 1, 5, 10, 25, 50 };

    public event Action<string, int, bool>? OnTrade;

    private CMUMarketsTerminalBuiState? _state;
    private string? _selected;

    public CMUMarketsTerminalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CrtLobbyTheme.ApplyWindow(this, useCrtTypography: true);

        BuyButton.OnPressed += _ => Trade(true);
        SellButton.OnPressed += _ => Trade(false);
        UnitsInput.OnTextChanged += _ => UpdateEstimate();

        foreach (var amount in Quick)
        {
            var button = new Button { Text = amount.ToString(), HorizontalExpand = true };
            button.OnPressed += _ =>
            {
                UnitsInput.Text = amount.ToString();
                UpdateEstimate();
            };
            QuickUnits.AddChild(button);
        }
    }

    private int Units => int.TryParse(UnitsInput.Text, out var units) ? Math.Clamp(units, 0, CMUMarketsLimits.MaxTradeUnits) : 0;

    private CMUMarketQuote? Selected => _state?.Quotes.FirstOrDefault(q => q.Id == _selected);

    private void Trade(bool buy)
    {
        if (_selected != null && Units > 0)
            OnTrade?.Invoke(_selected, Units, buy);
    }

    public void UpdateState(CMUMarketsTerminalBuiState state)
    {
        _state = state;
        if (_selected == null || state.Quotes.All(q => q.Id != _selected))
            _selected = state.Quotes.FirstOrDefault()?.Id;

        Title = Loc.GetString(state.Corporate ? "cmu-markets-title" : "cmu-markets-title-civilian");
        AccountLabel.Text = state.AccountName ?? Loc.GetString("cmu-markets-no-account");
        BalanceLabel.Text = state.AccountName == null ? string.Empty : Loc.GetString("cmu-markets-balance", ("amount", state.Balance));
        HoldingsLabel.Text = Loc.GetString("cmu-markets-holdings", ("value", state.HoldingsValue), ("cap", state.HoldingsCap));
        FeesLabel.Text = Loc.GetString("cmu-markets-fees", ("fee", state.FeePercent), ("dividend", state.DividendPercent));
        BuyButton.Disabled = state.AccountName == null;
        SellButton.Disabled = state.AccountName == null;

        RebuildWatchlist(state);
        RebuildNews(state);
        UpdateSelected();
        CrtLobbyTheme.Apply(this, useCrtTypography: true);
        UpdateTick();
    }

    private void RebuildWatchlist(CMUMarketsTerminalBuiState state)
    {
        QuoteRows.RemoveAllChildren();
        foreach (var quote in state.Quotes)
        {
            var id = quote.Id;
            var row = new Button
            {
                ToggleMode = true,
                Pressed = id == _selected,
                HorizontalExpand = true,
            };

            var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            line.AddChild(new Label { Text = quote.Symbol, MinWidth = 44 });
            line.AddChild(new Label { Text = $"{quote.Price:0.0}", HorizontalExpand = true, Align = Label.AlignMode.Right });
            line.AddChild(new Label
            {
                Text = $"{quote.ChangePercent:+0.0;-0.0;0.0}%",
                MinWidth = 64,
                Align = Label.AlignMode.Right,
                FontColorOverride = ChangeColor(quote.ChangePercent),
            });
            row.AddChild(line);

            row.OnPressed += _ =>
            {
                _selected = id;
                if (_state != null)
                    UpdateState(_state);
            };
            QuoteRows.AddChild(row);
        }
    }

    private void RebuildNews(CMUMarketsTerminalBuiState state)
    {
        NewsRows.RemoveAllChildren();
        if (state.News.Count == 0)
        {
            NewsRows.AddChild(new Label { Text = Loc.GetString("cmu-markets-no-news"), StyleClasses = { "LabelSubText" } });
            return;
        }

        foreach (var news in state.News)
        {
            var label = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(0, 1) };
            label.SetMessage(Loc.GetString("cmu-markets-news-line",
                ("time", $"{(int) news.At.TotalHours:00}:{news.At.Minutes:00}"),
                ("headline", news.Headline)));
            NewsRows.AddChild(label);
        }
    }

    private void UpdateSelected()
    {
        if (Selected is not { } quote)
            return;

        SymbolLabel.Text = quote.Symbol;
        NameLabel.Text = Loc.GetString(quote.Name);
        PriceLabel.Text = $"{quote.Price:0.00}";
        ChangeLabel.Text = $"{quote.ChangePercent:+0.00;-0.00;0.00}%";
        ChangeLabel.FontColorOverride = ChangeColor(quote.ChangePercent);
        Chart.SetData(quote.Candles, quote.NewsCandles);

        if (quote.Held > 0)
        {
            PositionLabel.Text = Loc.GetString("cmu-markets-position-held", ("held", quote.Held), ("symbol", quote.Symbol), ("average", quote.AverageCost));
            var profit = (int) (quote.Held * quote.Price - quote.Held * quote.AverageCost);
            ProfitLabel.Text = Loc.GetString("cmu-markets-pnl", ("amount", profit));
            ProfitLabel.FontColorOverride = ChangeColor(profit);
        }
        else
        {
            PositionLabel.Text = Loc.GetString("cmu-markets-position-none", ("symbol", quote.Symbol));
            ProfitLabel.Text = string.Empty;
        }

        UpdateEstimate();
    }

    private void UpdateEstimate()
    {
        if (Selected is not { } quote || _state == null)
        {
            EstimateLabel.Text = string.Empty;
            return;
        }

        var value = Units * quote.Price;
        EstimateLabel.Text = Loc.GetString("cmu-markets-estimate",
            ("buy", (int) MathF.Ceiling(value * (1 + _state.FeePercent / 100))),
            ("sell", (int) MathF.Floor(value * (1 - _state.FeePercent / 100))));
    }

    private static Color ChangeColor(float change)
    {
        return change >= 0 ? CrtTerminalPalette.Accent : CrtTerminalPalette.Alert;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTick();
    }

    private void UpdateTick()
    {
        if (_state == null)
            return;

        var remaining = _state.NextCandleAt - _timing.CurTime;
        TickLabel.Text = Loc.GetString("cmu-markets-next-tick", ("seconds", Math.Max(0, (int) Math.Ceiling(remaining.TotalSeconds))));
    }
}
