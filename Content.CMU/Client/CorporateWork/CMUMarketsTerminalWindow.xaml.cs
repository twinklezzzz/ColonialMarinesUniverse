using System.Linq;
using Content.Client.Lobby.UI;
using Content.Shared.CMU14.CorporateWork;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.CorporateWork;

[GenerateTypedNameReferences]
public sealed partial class CMUMarketsTerminalWindow : DefaultWindow
{
    [Dependency] private IGameTiming _timing = default!;

    public event Action<string, int, bool>? OnTrade;

    private CMUMarketsTerminalBuiState? _state;
    private string? _selected;

    public CMUMarketsTerminalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CrtLobbyTheme.ApplyWindow(this, useCrtTypography: true);

        BuyButton.OnPressed += _ => Trade(true);
        SellButton.OnPressed += _ => Trade(false);
    }

    private void Trade(bool buy)
    {
        if (_selected != null && int.TryParse(UnitsInput.Text, out var units) && units > 0)
            OnTrade?.Invoke(_selected, units, buy);
    }

    public void UpdateState(CMUMarketsTerminalBuiState state)
    {
        _state = state;
        if (_selected == null || state.Quotes.All(q => q.Id != _selected))
            _selected = state.Quotes.FirstOrDefault().Id;

        BudgetLabel.Text = Loc.GetString("cmu-markets-budget", ("amount", state.CorporateBudget));
        HoldingsLabel.Text = Loc.GetString("cmu-markets-holdings",
            ("value", state.HoldingsValue),
            ("cap", state.HoldingsCap),
            ("fee", state.FeePercent),
            ("dividend", state.DividendPercent));

        QuoteRows.RemoveAllChildren();
        foreach (var quote in state.Quotes)
        {
            var change = quote.PreviousPrice > 0 ? (quote.Price - quote.PreviousPrice) * 100f / quote.PreviousPrice : 0f;
            var text = Loc.GetString("cmu-markets-quote",
                ("name", Loc.GetString(quote.Name)),
                ("price", quote.Price),
                ("change", MathF.Round(change, 1)));
            if (quote.Held > 0)
                text += "\n" + Loc.GetString("cmu-markets-quote-held", ("held", quote.Held), ("average", quote.AverageCost));

            var id = quote.Id;
            var button = new Button
            {
                Text = text,
                ToggleMode = true,
                Pressed = id == _selected,
                HorizontalExpand = true,
            };
            button.OnPressed += _ =>
            {
                _selected = id;
                if (_state != null)
                    UpdateState(_state);
            };
            QuoteRows.AddChild(button);
        }

        NewsRows.RemoveAllChildren();
        if (state.News.Count == 0)
            NewsRows.AddChild(new Label { Text = Loc.GetString("cmu-markets-no-news"), StyleClasses = { "LabelSubText" } });

        foreach (var news in state.News)
        {
            NewsRows.AddChild(new RichTextLabel
            {
                Text = Loc.GetString("cmu-markets-news-line", ("headline", news.Headline)),
                HorizontalExpand = true,
                Margin = new Thickness(0, 1),
            });
        }

        CrtLobbyTheme.Apply(this, useCrtTypography: true);
        UpdateTick();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTick();
    }

    private void UpdateTick()
    {
        if (_state == null)
            return;

        var remaining = _state.NextTickAt - _timing.CurTime;
        TickLabel.Text = Loc.GetString("cmu-markets-next-tick", ("seconds", Math.Max(0, (int) Math.Ceiling(remaining.TotalSeconds))));
    }
}
