using System.Linq;
using Content.Client.Lobby.UI;
using Content.Shared.CMU14.CorporateWork;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.CorporateWork;

[GenerateTypedNameReferences]
public sealed partial class CMUAuditTerminalWindow : DefaultWindow
{
    [Dependency] private IGameTiming _timing = default!;

    public event Action<int>? OnStart;
    public event Action<List<int>>? OnSubmit;

    private readonly List<Button> _reportButtons = new();
    private CMUAuditTerminalBuiState? _state;

    public CMUAuditTerminalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CrtLobbyTheme.ApplyWindow(this, useCrtTypography: true);
        CMUTerminalLayout.StylePanel(WorkPanel);

        SubmitButton.OnPressed += _ =>
        {
            var flagged = _reportButtons
                .Select((button, index) => (button, index))
                .Where(pair => pair.button.Pressed)
                .Select(pair => pair.index)
                .ToList();
            OnSubmit?.Invoke(flagged);
        };
    }

    public void UpdateState(CMUAuditTerminalBuiState state)
    {
        var previous = _state;
        _state = state;

        TierButtons.RemoveAllChildren();
        for (var i = 0; i < state.Tiers.Count; i++)
        {
            var tier = state.Tiers[i];
            var index = i;
            var button = new Button
            {
                Text = Loc.GetString("cmu-audit-tier",
                    ("name", Loc.GetString(tier.Name)),
                    ("rows", tier.Rows),
                    ("errors", tier.Errors),
                    ("reward", tier.Reward)),
                HorizontalExpand = true,
                MinHeight = 34,
            };
            button.OnPressed += _ => OnStart?.Invoke(index);
            TierButtons.AddChild(button);
        }

        LedgerRows.RemoveAllChildren();
        for (var i = 0; i < state.Ledger.Count; i++)
        {
            LedgerRows.AddChild(CMUTerminalLayout.Row(new Label { Text = FormatEntry(state.Ledger[i]) }, i));
        }

        // Another player opening the terminal re-sends the same case; keep this player's flags.
        var sameCase = previous != null && previous.Report.SequenceEqual(state.Report);
        var flags = _reportButtons.Select(b => b.Pressed).ToList();
        ReportRows.RemoveAllChildren();
        _reportButtons.Clear();
        for (var i = 0; i < state.Report.Count; i++)
        {
            var button = new Button
            {
                Text = FormatEntry(state.Report[i]),
                ToggleMode = true,
                Pressed = sameCase && i < flags.Count && flags[i],
                HorizontalExpand = true,
                MinHeight = 32,
                ToolTip = Loc.GetString("cmu-audit-flag-tooltip"),
            };
            _reportButtons.Add(button);
            ReportRows.AddChild(button);
        }

        SubmitButton.Disabled = state.ActiveTier == null;
        UpdateStatus();

        // Rows are rebuilt on every update, so they need the theme again.
        CrtLobbyTheme.Apply(this, useCrtTypography: true);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_state is { ActiveTier: null } && _state.NextCaseAt > _timing.CurTime)
            UpdateStatus();
    }

    private void UpdateStatus()
    {
        if (_state == null)
            return;

        if (_state.ActiveTier is { } active)
        {
            StatusLabel.Text = Loc.GetString("cmu-audit-status-active",
                ("name", Loc.GetString(_state.Tiers[active].Name)),
                ("errors", _state.Tiers[active].Errors));
            return;
        }

        var lines = new List<string>();
        if (_state.LastResult is { } result)
        {
            lines.Add(Loc.GetString("cmu-audit-status-result",
                ("found", result.Found),
                ("missed", result.Missed),
                ("false", result.FalseFlags),
                ("payout", result.Payout)));
        }

        var remaining = _state.NextCaseAt - _timing.CurTime;
        lines.Add(remaining > TimeSpan.Zero
            ? Loc.GetString("cmu-audit-status-cooldown", ("seconds", (int) Math.Ceiling(remaining.TotalSeconds)))
            : Loc.GetString("cmu-audit-status-idle"));

        StatusLabel.Text = string.Join("\n", lines);
    }

    private static string FormatEntry(CMUAuditEntry entry)
    {
        return Loc.GetString("cmu-audit-entry",
            ("item", Loc.GetString(entry.Item)),
            ("department", Loc.GetString(entry.Department)),
            ("amount", entry.Amount));
    }
}
