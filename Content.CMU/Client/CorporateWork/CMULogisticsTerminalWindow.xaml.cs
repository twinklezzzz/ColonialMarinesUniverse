using System.Linq;
using Content.Client.Lobby.UI;
using Content.Shared.CMU14.CorporateWork;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.CorporateWork;

[GenerateTypedNameReferences]
public sealed partial class CMULogisticsTerminalWindow : DefaultWindow
{
    [Dependency] private IGameTiming _timing = default!;

    public event Action<int>? OnStart;
    public event Action<List<int>>? OnSubmit;

    private readonly List<Button> _crateButtons = new();
    private CMULogisticsTerminalBuiState? _state;

    public CMULogisticsTerminalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CrtLobbyTheme.ApplyWindow(this, useCrtTypography: true);
        SubmitButton.OnPressed += _ => OnSubmit?.Invoke(LoadedIndexes().ToList());
    }

    public void UpdateState(CMULogisticsTerminalBuiState state)
    {
        var previous = _state;
        _state = state;

        TierButtons.RemoveAllChildren();
        for (var i = 0; i < state.Tiers.Count; i++)
        {
            var tier = state.Tiers[i];
            var index = i;
            var button = new Button
            {
                Text = Loc.GetString("cmu-logistics-tier",
                    ("name", Loc.GetString(tier.Name)),
                    ("crates", tier.Crates),
                    ("reward", tier.Reward)),
                HorizontalExpand = true,
            };
            button.OnPressed += _ => OnStart?.Invoke(index);
            TierButtons.AddChild(button);
        }

        // Another player opening the terminal re-sends the same manifest; keep this player's picks.
        var sameCase = previous != null && previous.Crates.SequenceEqual(state.Crates);
        var picks = _crateButtons.Select(b => b.Pressed).ToList();
        CrateRows.RemoveAllChildren();
        _crateButtons.Clear();
        for (var i = 0; i < state.Crates.Count; i++)
        {
            var crate = state.Crates[i];
            var button = new Button
            {
                Text = Loc.GetString("cmu-logistics-crate",
                    ("item", Loc.GetString(crate.Item)),
                    ("weight", crate.Weight),
                    ("hazard", crate.Hazard),
                    ("value", crate.Value)),
                ToggleMode = true,
                Pressed = sameCase && i < picks.Count && picks[i],
                HorizontalExpand = true,
            };
            button.OnToggled += _ => UpdateTotals();
            _crateButtons.Add(button);
            CrateRows.AddChild(button);
        }

        UpdateTotals();
        UpdateStatus();

        // Rows are rebuilt on every update, so they need the theme again.
        CrtLobbyTheme.Apply(this, useCrtTypography: true);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_state is { ActiveTier: null } && _state.NextCaseAt > _timing.CurTime)
            UpdateStatus();
    }

    private IEnumerable<int> LoadedIndexes()
    {
        return _crateButtons
            .Select((button, index) => (button, index))
            .Where(pair => pair.button.Pressed)
            .Select(pair => pair.index);
    }

    private void UpdateTotals()
    {
        if (_state is not { ActiveTier: not null } state)
        {
            TotalsLabel.Text = string.Empty;
            SubmitButton.Disabled = true;
            return;
        }

        var loaded = LoadedIndexes().Select(i => state.Crates[i]).ToList();
        var weight = loaded.Sum(c => c.Weight);
        var hazard = loaded.Sum(c => c.Hazard);
        var overloaded = weight > state.WeightLimit || hazard > state.HazardLimit;

        TotalsLabel.Text = Loc.GetString("cmu-logistics-totals",
            ("weight", weight),
            ("weightLimit", state.WeightLimit),
            ("hazard", hazard),
            ("hazardLimit", state.HazardLimit),
            ("value", loaded.Sum(c => c.Value)));
        TotalsLabel.StyleClasses.Clear();
        if (overloaded)
            TotalsLabel.StyleClasses.Add("Caution");

        SubmitButton.Disabled = overloaded || loaded.Count == 0;
    }

    private void UpdateStatus()
    {
        if (_state == null)
            return;

        if (_state.ActiveTier is { } active)
        {
            StatusLabel.Text = Loc.GetString("cmu-logistics-status-active", ("name", Loc.GetString(_state.Tiers[active].Name)));
            return;
        }

        var lines = new List<string>();
        if (_state.LastResult is { } result)
        {
            lines.Add(Loc.GetString("cmu-logistics-status-result",
                ("value", result.Value),
                ("best", result.BestValue),
                ("payout", result.Payout)));
        }

        var remaining = _state.NextCaseAt - _timing.CurTime;
        lines.Add(remaining > TimeSpan.Zero
            ? Loc.GetString("cmu-logistics-status-cooldown", ("seconds", (int) Math.Ceiling(remaining.TotalSeconds)))
            : Loc.GetString("cmu-logistics-status-idle"));

        StatusLabel.Text = string.Join("\n", lines);
    }
}
