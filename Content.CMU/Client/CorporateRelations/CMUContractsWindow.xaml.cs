using System.Linq;
using Content.Client.CMU14.Interface;
using Content.Client.Lobby.UI;
using Content.Shared.CMU14.CorporateRelations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.CMU14.CorporateRelations;

[GenerateTypedNameReferences]
public sealed partial class CMUContractsWindow : DefaultWindow
{
    [Dependency] private IGameTiming _timing = default!;

    public event Action<int>? OnSetRent;
    public event Action<bool>? OnSetResearchLicense;
    public event Action<bool>? OnSetTaxBreak;
    public event Action<string, int, int>? OnPostOrder;
    public event Action<int>? OnCancelOrder;
    public event Action? OnFreezeOrders;
    public event Action<int>? OnRequestLoan;
    public event Action<string, int, int>? OnCounterLoan;
    public event Action<string, bool>? OnAnswerLoan;
    public event Action<string>? OnCallInLoan;
    public event Action<bool>? OnWithdrawal;

    private CMUContractsBuiState? _state;

    public CMUContractsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TabContainer.SetTabTitle(LeaseTab, Loc.GetString("cmu-contracts-section-rent"));
        TabContainer.SetTabTitle(OrdersTab, Loc.GetString("cmu-contracts-section-orders"));
        TabContainer.SetTabTitle(LoansTab, Loc.GetString("cmu-contracts-section-loans"));
        TabContainer.SetTabTitle(WithdrawalTab, Loc.GetString("cmu-contracts-section-withdrawal"));
        CrtLobbyTheme.ApplyWindow(this, useCrtTypography: true);
        CrtLobbyTheme.ApplyToOptionButton(GoodSelect);

        SetRentButton.OnPressed += _ =>
        {
            if (int.TryParse(RentInput.Text, out var rent))
                OnSetRent?.Invoke(rent);
        };
        ResearchButton.OnPressed += _ => OnSetResearchLicense?.Invoke(!(_state?.ResearchLicense ?? true));
        TaxButton.OnPressed += _ => OnSetTaxBreak?.Invoke(!(_state?.TaxBreak ?? true));

        GoodSelect.OnItemSelected += args =>
        {
            GoodSelect.SelectId(args.Id);
            UpdateOrderCost();
        };
        QuantityInput.OnTextChanged += _ => UpdateOrderCost();
        PremiumInput.OnTextChanged += _ => UpdateOrderCost();
        PostOrderButton.OnPressed += _ =>
        {
            if (SelectedGood() is { } good &&
                int.TryParse(QuantityInput.Text, out var quantity) &&
                int.TryParse(PremiumInput.Text, out var premium))
            {
                OnPostOrder?.Invoke(good.Id, quantity, premium);
            }
        };
        FreezeOrdersButton.OnPressed += _ => OnFreezeOrders?.Invoke();

        RequestLoanButton.OnPressed += _ =>
        {
            if (int.TryParse(LoanAmountInput.Text, out var amount))
                OnRequestLoan?.Invoke(amount);
        };

        WithdrawalButton.OnPressed += _ => OnWithdrawal?.Invoke(true);
    }

    public void UpdateState(CMUContractsBuiState state)
    {
        var previous = _state;
        _state = state;
        var corporate = state.Side == CMUContractsSide.Corporate;

        BudgetsLabel.Text = state.Borrower == null
            ? Loc.GetString("cmu-contracts-budget-corporate", ("amount", state.CorporateBudget))
            : Loc.GetString("cmu-contracts-budget-borrower", ("amount", state.BorrowerBudget), ("corporate", state.CorporateBudget));

        // Rent and licences
        RentLabel.Text = state.CorporateArrears > 0
            ? Loc.GetString("cmu-contracts-rent-arrears", ("rent", state.Rent), ("cap", state.RentCap), ("arrears", state.CorporateArrears))
            : Loc.GetString("cmu-contracts-rent", ("rent", state.Rent), ("cap", state.RentCap));
        LicenceLabel.Text = Loc.GetString("cmu-contracts-licences",
            ("research", Loc.GetString(state.ResearchLicense ? "cmu-contracts-granted" : "cmu-contracts-revoked")),
            ("tax", Loc.GetString(state.TaxBreak ? "cmu-contracts-granted" : "cmu-contracts-revoked")));
        ColonyControls.Visible = state.Side == CMUContractsSide.Colony;
        ResearchButton.Text = Loc.GetString(state.ResearchLicense ? "cmu-contracts-revoke-research" : "cmu-contracts-grant-research");
        TaxButton.Text = Loc.GetString(state.TaxBreak ? "cmu-contracts-revoke-tax" : "cmu-contracts-grant-tax");
        if (previous == null)
            RentInput.Text = state.Rent.ToString();

        // Work orders
        if (previous == null || !previous.WorkOrders.SequenceEqual(state.WorkOrders))
            BuildOrders(state, corporate);

        CorporateOrderControls.Visible = corporate && !state.Withdrawn;
        FreezeOrdersButton.Disabled = state.WorkOrdersFrozen;
        if (previous == null || !previous.Goods.SequenceEqual(state.Goods))
        {
            GoodSelect.Clear();
            for (var i = 0; i < state.Goods.Count; i++)
            {
                GoodSelect.AddItem(Loc.GetString(state.Goods[i].Name), i);
            }
        }

        UpdateOrderCost();

        // Loans
        LoansDescription.Text = Loc.GetString(corporate ? "cmu-contracts-loans-description-corporate" : "cmu-contracts-loans-description-borrower");
        if (previous == null || !previous.Loans.SequenceEqual(state.Loans))
            BuildLoans(state, corporate);

        RequestLoanControls.Visible = !corporate && !state.Withdrawn && state.Loans.All(l => l.Borrower != state.Borrower);

        // Withdrawal
        TabContainer.SetTabVisible(WithdrawalTab, corporate && !state.Withdrawn);
        // Once ordered a withdrawal can't be called off.
        WithdrawalButton.Text = Loc.GetString(state.WithdrawalAt == null ? "cmu-contracts-withdrawal-start" : "cmu-contracts-withdrawal-locked");
        WithdrawalButton.Disabled = state.WithdrawalAt != null;

        UpdateTimers();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTimers();
    }

    private void UpdateTimers()
    {
        if (_state == null)
            return;

        CycleLabel.Text = Loc.GetString("cmu-contracts-next-cycle", ("time", Format(_state.NextCycleAt - _timing.CurTime)));

        WithdrawalLabel.Visible = _state.Withdrawn || _state.WithdrawalAt != null;
        var warning = _state.Withdrawn
            ? Loc.GetString("cmu-contracts-withdrawn")
            : _state.WithdrawalAt is { } at
                ? Loc.GetString("cmu-contracts-withdrawal-countdown", ("time", Format(at - _timing.CurTime)))
                : string.Empty;
        WithdrawalLabel.SetMessage(FormattedMessage.FromUnformatted(warning), CrtTerminalPalette.Alert);
    }

    private static string Format(TimeSpan time)
    {
        if (time < TimeSpan.Zero)
            time = TimeSpan.Zero;

        return $"{(int) time.TotalMinutes}:{time.Seconds:00}";
    }

    private CMUWorkOrderGoodInfo? SelectedGood()
    {
        if (_state == null || GoodSelect.SelectedId < 0 || GoodSelect.SelectedId >= _state.Goods.Count)
            return null;

        return _state.Goods[GoodSelect.SelectedId];
    }

    private void UpdateOrderCost()
    {
        if (_state == null || SelectedGood() is not { } good)
        {
            OrderCostLabel.Text = string.Empty;
            return;
        }

        int.TryParse(QuantityInput.Text, out var quantity);
        int.TryParse(PremiumInput.Text, out var premium);
        quantity = Math.Clamp(quantity, 0, good.MaxQuantity);
        var escrow = (int) MathF.Ceiling(quantity * good.UnitValue * premium / 100f);
        OrderCostLabel.Text = Loc.GetString("cmu-contracts-order-cost",
            ("value", good.UnitValue),
            ("max", good.MaxQuantity),
            ("maxPremium", _state.MaxPremiumPercent),
            ("escrow", escrow));
    }

    private void BuildOrders(CMUContractsBuiState state, bool corporate)
    {
        OrderRows.RemoveAllChildren();
        if (state.WorkOrders.Count == 0)
        {
            OrderRows.AddChild(new Label { Text = Loc.GetString("cmu-contracts-no-orders"), StyleClasses = { "LabelSubText" } });
            return;
        }

        foreach (var order in state.WorkOrders)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            row.AddChild(new RichTextLabel
            {
                Text = Loc.GetString("cmu-contracts-order",
                    ("good", Loc.GetString(order.Good)),
                    ("delivered", order.Delivered),
                    ("quantity", order.Quantity),
                    ("premium", order.PremiumPercent)),
                HorizontalExpand = true,
            });

            if (corporate)
            {
                var id = order.Id;
                var cancel = new Button { Text = Loc.GetString("cmu-contracts-cancel-order") };
                cancel.OnPressed += _ => OnCancelOrder?.Invoke(id);
                row.AddChild(cancel);
            }

            OrderRows.AddChild(row);
        }

        CrtLobbyTheme.Apply(OrderRows, useCrtTypography: true);
    }

    private void BuildLoans(CMUContractsBuiState state, bool corporate)
    {
        LoanRows.RemoveAllChildren();
        if (state.Loans.Count == 0)
        {
            LoanRows.AddChild(new Label { Text = Loc.GetString("cmu-contracts-no-loans"), StyleClasses = { "LabelSubText" } });
            return;
        }

        foreach (var loan in state.Loans)
        {
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 2) };
            var borrower = loan.Borrower;

            if (loan.Stage == CMULoanStage.Active)
            {
                box.AddChild(new RichTextLabel
                {
                    Text = Loc.GetString(loan.StartingDebt ? "cmu-contracts-loan-starting-debt" : "cmu-contracts-loan-active",
                        ("borrower", loan.BorrowerName),
                        ("owed", loan.Owed),
                        ("interest", loan.InterestPercent),
                        ("left", loan.InstallmentsLeft)),
                });

                if (corporate && !state.Withdrawn)
                {
                    var callIn = new Button { Text = Loc.GetString("cmu-contracts-call-in") };
                    callIn.OnPressed += _ => OnCallInLoan?.Invoke(borrower);
                    box.AddChild(callIn);
                }

                LoanRows.AddChild(box);
                continue;
            }

            var ourTurn = corporate == (loan.Stage == CMULoanStage.AwaitingCorporate);
            box.AddChild(new RichTextLabel
            {
                Text = Loc.GetString(ourTurn ? "cmu-contracts-loan-our-turn" : "cmu-contracts-loan-their-turn",
                    ("borrower", loan.BorrowerName),
                    ("amount", loan.Amount),
                    ("interest", loan.InterestPercent)),
            });

            if (ourTurn)
            {
                var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
                var amount = new LineEdit { Text = loan.Amount.ToString(), PlaceHolder = Loc.GetString("cmu-contracts-amount"), HorizontalExpand = true };
                var interest = new LineEdit { Text = loan.InterestPercent.ToString(), PlaceHolder = Loc.GetString("cmu-contracts-interest"), MinWidth = 60 };
                var counter = new Button { Text = Loc.GetString("cmu-contracts-counter") };
                counter.OnPressed += _ =>
                {
                    if (int.TryParse(amount.Text, out var a) && int.TryParse(interest.Text, out var i))
                        OnCounterLoan?.Invoke(borrower, a, i);
                };
                var accept = new Button { Text = Loc.GetString("cmu-contracts-accept") };
                accept.OnPressed += _ => OnAnswerLoan?.Invoke(borrower, true);
                var decline = new Button { Text = Loc.GetString("cmu-contracts-decline") };
                decline.OnPressed += _ => OnAnswerLoan?.Invoke(borrower, false);

                // Terms on one row, the answer on the next, so the window stays narrow.
                row.AddChild(amount);
                row.AddChild(interest);
                row.AddChild(counter);
                box.AddChild(row);

                var answer = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
                accept.HorizontalExpand = true;
                decline.HorizontalExpand = true;
                answer.AddChild(accept);
                answer.AddChild(decline);
                box.AddChild(answer);
            }

            LoanRows.AddChild(box);
        }

        CrtLobbyTheme.Apply(LoanRows, useCrtTypography: true);
    }
}
